// font is glyphArt as a row of bits for each of the seven rows of each glyph, the leftmost column being
// the highest of the five bits.
var font [95][fontHeight]uint8

func init() {
	for i, art := range glyphArt {
		bits, err := parseGlyph(art)
		if err != nil {
			panic("engine: the glyph for " + string(rune(' '+i)) + ": " + err.Error())
		}
		font[i] = bits
	}
}

// parseGlyph reads a glyph drawn as seven rows of five columns, '#' for a pixel and '.' for none, into
// a row of bits for each row, the leftmost column being the highest of the five.
func parseGlyph(art string) (bits [fontHeight]uint8, err error) {
	rows := strings.Fields(art)
	if len(rows) != fontHeight {
		return bits, errors.New("not seven rows")
	}
	for y, row := range rows {
		if len(row) != fontWidth {
			return bits, errors.New("a row is not five columns")
		}
		for x := range fontWidth {
			switch row[x] {
			case '#':
				bits[y] |= 1 << (fontWidth - 1 - x)
			case '.':
			default:
				return bits, errors.New("a character that is neither a hash nor a dot")
			}
		}
	}
	return bits, nil
}
